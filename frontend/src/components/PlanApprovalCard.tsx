import React, { useState } from "react";
import { CheckCircle2, Edit3, Plus, RefreshCw, ShieldCheck, Trash2, XCircle } from "lucide-react";
import type { PlanOut, SubTask } from "../types/api";
import { api } from "../services/api";

interface Props {
  researchId: string;
  planOut: PlanOut;
  onUpdated: (p: PlanOut) => void;
  onResumed: () => void;
}

export const PlanApprovalCard: React.FC<Props> = ({ researchId, planOut, onUpdated, onResumed }) => {
  const plan = planOut.plan;
  const [editing, setEditing] = useState(false);
  const [objectives, setObjectives] = useState<string[]>(plan?.objectives || []);
  const [subtasks, setSubtasks] = useState<SubTask[]>(plan?.subtasks || []);
  const [outline, setOutline] = useState<string[]>(plan?.report_outline || []);
  const [note, setNote] = useState("");
  const [rejectFeedback, setRejectFeedback] = useState("");
  const [showReject, setShowReject] = useState(false);
  const [busy, setBusy] = useState(false);
  const [err, setErr] = useState<string | null>(null);

  if (!plan) return null;

  const startEdit = () => {
    setObjectives([...plan.objectives]);
    setSubtasks(plan.subtasks.map((t) => ({ ...t, search_queries: [...t.search_queries], depends_on: [...t.depends_on] })));
    setOutline([...plan.report_outline]);
    setEditing(true);
    setErr(null);
  };

  const handleSavePatch = async () => {
    setBusy(true);
    setErr(null);
    try {
      const updated = await api.patchPlan(researchId, {
        objectives: objectives.map((o) => o.trim()).filter(Boolean),
        subtasks,
        report_outline: outline.map((o) => o.trim()).filter(Boolean),
      });
      onUpdated(updated);
      setEditing(false);
    } catch (e: any) {
      setErr(e.message || "Failed to update plan");
    } finally {
      setBusy(false);
    }
  };

  const handleReject = async () => {
    if (!rejectFeedback.trim()) return;
    setBusy(true);
    setErr(null);
    try {
      const updated = await api.rejectPlan(researchId, rejectFeedback.trim());
      onUpdated(updated);
      setRejectFeedback("");
      setShowReject(false);
    } catch (e: any) {
      setErr(e.message || "Failed to regenerate plan");
    } finally {
      setBusy(false);
    }
  };

  const handleApprove = async () => {
    setBusy(true);
    setErr(null);
    try {
      const updated = await api.approvePlan(researchId, note, true);
      onUpdated(updated);
      onResumed();
    } catch (e: any) {
      setErr(e.message || "Failed to approve plan");
    } finally {
      setBusy(false);
    }
  };

  const addSubtask = () => {
    const nextNum = subtasks.length + 1;
    const defaultAgent = plan.mode === "document" ? "document" : "search";
    setSubtasks([
      ...subtasks,
      {
        id: `t${nextNum}`,
        description: "Investigate additional aspect",
        agent: defaultAgent,
        search_queries: ["additional query"],
        depends_on: [],
      },
    ]);
  };

  return (
    <div className="rounded-xl border border-amber-500/40 bg-slate-900/80 p-5 shadow-lg">
      <div className="flex flex-wrap items-center justify-between gap-3 border-b border-slate-800 pb-4">
        <div>
          <div className="flex items-center gap-2">
            <ShieldCheck className="h-5 w-5 text-amber-400" />
            <h3 className="text-base font-semibold text-white">
              Research Plan {planOut.status === "awaiting_approval" ? "— Human Approval Required" : ""}
            </h3>
          </div>
          <p className="mt-1 text-xs text-slate-400">
            Generated by <span className="font-mono text-slate-300">{plan.generated_by}</span> · Budget:{" "}
            {plan.budget.max_subtasks} subtasks, {plan.budget.max_sources} sources, {plan.budget.max_revisions} revisions
          </p>
        </div>

        <div className="flex flex-wrap items-center gap-2">
          {!editing && (planOut.status === "awaiting_approval" || planOut.status === "planned") && (
            <>
              <button
                onClick={startEdit}
                disabled={busy}
                className="inline-flex items-center gap-1.5 rounded-lg border border-slate-700 bg-slate-800 px-3 py-1.5 text-xs font-medium text-slate-200 hover:bg-slate-700"
              >
                <Edit3 className="h-3.5 w-3.5" /> Edit Plan
              </button>
              <button
                onClick={() => setShowReject((v) => !v)}
                disabled={busy}
                className="inline-flex items-center gap-1.5 rounded-lg border border-rose-500/40 bg-rose-950/40 px-3 py-1.5 text-xs font-medium text-rose-300 hover:bg-rose-900/40"
              >
                <RefreshCw className="h-3.5 w-3.5" /> Reject &amp; Replan
              </button>
            </>
          )}
        </div>
      </div>

      {err && (
        <div className="mt-3 rounded-lg border border-rose-500/40 bg-rose-950/50 px-3 py-2 text-xs text-rose-200">
          {err}
        </div>
      )}

      {showReject && !editing && (
        <div className="mt-4 rounded-lg border border-rose-500/30 bg-slate-950/70 p-3">
          <label className="block text-xs font-medium text-rose-300">
            Guidance for Supervisor re-planning:
          </label>
          <textarea
            rows={2}
            value={rejectFeedback}
            onChange={(e) => setRejectFeedback(e.target.value)}
            placeholder="e.g., Focus more on benchmark comparisons and security limitations..."
            className="mt-1.5 w-full rounded-lg border border-slate-700 bg-slate-900 px-3 py-2 text-xs text-slate-100 focus:border-indigo-500 focus:outline-none"
          />
          <div className="mt-2 flex justify-end gap-2">
            <button
              onClick={() => setShowReject(false)}
              className="rounded-md px-2.5 py-1 text-xs text-slate-400 hover:text-slate-200"
            >
              Cancel
            </button>
            <button
              onClick={handleReject}
              disabled={busy || rejectFeedback.trim().length < 3}
              className="rounded-md bg-rose-600 px-3 py-1 text-xs font-medium text-white hover:bg-rose-500 disabled:opacity-50"
            >
              {busy ? "Regenerating..." : "Regenerate Plan"}
            </button>
          </div>
        </div>
      )}

      <div className="mt-4 grid gap-4 md:grid-cols-2">
        <div>
          <h4 className="text-xs font-semibold uppercase tracking-wider text-slate-400">Objectives</h4>
          {editing ? (
            <div className="mt-2 space-y-2">
              {objectives.map((obj, idx) => (
                <div key={idx} className="flex gap-1.5">
                  <input
                    value={obj}
                    onChange={(e) => {
                      const copy = [...objectives];
                      copy[idx] = e.target.value;
                      setObjectives(copy);
                    }}
                    className="w-full rounded border border-slate-700 bg-slate-950 px-2.5 py-1 text-xs text-slate-100"
                  />
                  {objectives.length > 1 && (
                    <button
                      onClick={() => setObjectives(objectives.filter((_, i) => i !== idx))}
                      className="text-slate-500 hover:text-rose-400"
                    >
                      <Trash2 className="h-3.5 w-3.5" />
                    </button>
                  )}
                </div>
              ))}
              <button
                onClick={() => setObjectives([...objectives, "New objective"])}
                className="inline-flex items-center gap-1 text-xs text-indigo-400 hover:text-indigo-300"
              >
                <Plus className="h-3 w-3" /> Add objective
              </button>
            </div>
          ) : (
            <ul className="mt-2 list-disc space-y-1 pl-4 text-xs text-slate-200">
              {plan.objectives.map((o, i) => (
                <li key={i}>{o}</li>
              ))}
            </ul>
          )}
        </div>

        <div>
          <h4 className="text-xs font-semibold uppercase tracking-wider text-slate-400">Report Outline</h4>
          {editing ? (
            <div className="mt-2 space-y-2">
              {outline.map((sec, idx) => (
                <div key={idx} className="flex gap-1.5">
                  <input
                    value={sec}
                    onChange={(e) => {
                      const copy = [...outline];
                      copy[idx] = e.target.value;
                      setOutline(copy);
                    }}
                    className="w-full rounded border border-slate-700 bg-slate-950 px-2.5 py-1 text-xs text-slate-100"
                  />
                  {outline.length > 2 && (
                    <button
                      onClick={() => setOutline(outline.filter((_, i) => i !== idx))}
                      className="text-slate-500 hover:text-rose-400"
                    >
                      <Trash2 className="h-3.5 w-3.5" />
                    </button>
                  )}
                </div>
              ))}
              <button
                onClick={() => setOutline([...outline, "New section"])}
                className="inline-flex items-center gap-1 text-xs text-indigo-400 hover:text-indigo-300"
              >
                <Plus className="h-3 w-3" /> Add section
              </button>
            </div>
          ) : (
            <ol className="mt-2 list-decimal space-y-1 pl-4 text-xs text-slate-200">
              {plan.report_outline.map((o, i) => (
                <li key={i}>{o}</li>
              ))}
            </ol>
          )}
        </div>
      </div>

      <div className="mt-4">
        <div className="flex items-center justify-between">
          <h4 className="text-xs font-semibold uppercase tracking-wider text-slate-400">
            Subtasks ({editing ? subtasks.length : plan.subtasks.length}/{plan.budget.max_subtasks})
          </h4>
          {editing && subtasks.length < plan.budget.max_subtasks && (
            <button
              onClick={addSubtask}
              className="inline-flex items-center gap-1 text-xs text-indigo-400 hover:text-indigo-300"
            >
              <Plus className="h-3.5 w-3.5" /> Add Subtask
            </button>
          )}
        </div>

        <div className="mt-2 space-y-2">
          {(editing ? subtasks : plan.subtasks).map((st, idx) => (
            <div key={st.id} className="rounded-lg border border-slate-800 bg-slate-950/70 p-3 text-xs">
              {editing ? (
                <div className="space-y-2">
                  <div className="flex items-center gap-2">
                    <span className="font-mono font-semibold text-indigo-400">{st.id}</span>
                    <select
                      value={st.agent}
                      onChange={(e) => {
                        const copy = [...subtasks];
                        copy[idx] = { ...st, agent: e.target.value as "search" | "document" };
                        setSubtasks(copy);
                      }}
                      className="rounded border border-slate-700 bg-slate-900 px-2 py-1 text-xs text-slate-100"
                    >
                      <option value="search">search</option>
                      <option value="document">document</option>
                    </select>
                    <input
                      value={st.description}
                      onChange={(e) => {
                        const copy = [...subtasks];
                        copy[idx] = { ...st, description: e.target.value };
                        setSubtasks(copy);
                      }}
                      className="flex-1 rounded border border-slate-700 bg-slate-900 px-2.5 py-1 text-xs text-slate-100"
                    />
                    {subtasks.length > 1 && (
                      <button
                        onClick={() => setSubtasks(subtasks.filter((_, i) => i !== idx))}
                        className="text-slate-500 hover:text-rose-400"
                      >
                        <Trash2 className="h-3.5 w-3.5" />
                      </button>
                    )}
                  </div>
                  <input
                    value={st.search_queries.join(", ")}
                    onChange={(e) => {
                      const copy = [...subtasks];
                      copy[idx] = {
                        ...st,
                        search_queries: e.target.value.split(",").map((q) => q.trim()).filter(Boolean),
                      };
                      setSubtasks(copy);
                    }}
                    placeholder="Comma-separated queries"
                    className="w-full rounded border border-slate-800 bg-slate-900 px-2.5 py-1 text-xs text-slate-300"
                  />
                </div>
              ) : (
                <div className="flex flex-wrap items-start justify-between gap-2">
                  <div>
                    <span className="mr-2 rounded bg-indigo-500/20 px-1.5 py-0.5 font-mono text-[11px] font-semibold text-indigo-300">
                      {st.id}
                    </span>
                    <span className="mr-2 rounded bg-slate-800 px-1.5 py-0.5 font-mono text-[11px] text-slate-300">
                      {st.agent}
                    </span>
                    <span className="font-medium text-slate-100">{st.description}</span>
                    <div className="mt-1 text-[11px] text-slate-400">
                      Queries: {st.search_queries.map((q) => `"${q}"`).join(" · ")}
                    </div>
                  </div>
                  {st.depends_on.length > 0 && (
                    <span className="text-[11px] text-slate-500">depends on: {st.depends_on.join(", ")}</span>
                  )}
                </div>
              )}
            </div>
          ))}
        </div>
      </div>

      {editing ? (
        <div className="mt-4 flex justify-end gap-2 border-t border-slate-800 pt-3">
          <button
            onClick={() => setEditing(false)}
            className="inline-flex items-center gap-1 rounded-lg border border-slate-700 px-3 py-1.5 text-xs text-slate-300 hover:bg-slate-800"
          >
            <XCircle className="h-3.5 w-3.5" /> Cancel
          </button>
          <button
            onClick={handleSavePatch}
            disabled={busy}
            className="inline-flex items-center gap-1.5 rounded-lg bg-indigo-600 px-4 py-1.5 text-xs font-semibold text-white hover:bg-indigo-500 disabled:opacity-50"
          >
            Save Plan Changes
          </button>
        </div>
      ) : (
        planOut.status === "awaiting_approval" && (
          <div className="mt-4 flex flex-wrap items-center gap-3 border-t border-slate-800 pt-4">
            <input
              value={note}
              onChange={(e) => setNote(e.target.value)}
              placeholder="Optional approval note for audit trace..."
              className="flex-1 rounded-lg border border-slate-700 bg-slate-950 px-3 py-1.5 text-xs text-slate-100 focus:border-emerald-500 focus:outline-none"
            />
            <button
              onClick={handleApprove}
              disabled={busy}
              className="inline-flex items-center gap-1.5 rounded-lg bg-emerald-600 px-4 py-2 text-xs font-semibold text-white shadow hover:bg-emerald-500 disabled:opacity-50"
            >
              <CheckCircle2 className="h-4 w-4" />
              {busy ? "Starting Workflow..." : "Approve & Run Research"}
            </button>
          </div>
        )
      )}
    </div>
  );
};
